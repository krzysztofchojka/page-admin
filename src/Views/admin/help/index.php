<div class="max-w-4xl mx-auto mt-6">
    <h1 class="text-3xl font-bold text-gray-800 mb-2">Jak korzystać z systemu? 💡</h1>
    <p class="text-gray-500 mb-8">Krótki poradnik krok po kroku stworzony z myślą o łatwym zarządzaniu stroną.</p>

    <div class="space-y-6">
        <div class="bg-white p-6 rounded-xl shadow-sm border border-gray-200">
            <h3 class="text-xl font-bold text-blue-600 mb-3 flex items-center gap-2"><span>📄</span> Jak edytować teksty na stronie?</h3>
            <p class="text-gray-700 leading-relaxed mb-4">
                Przejdź do zakładki <b>Strony</b> w lewym menu i kliknij "Edytuj" obok wybranej strony. Zobaczysz edytor blokowy. 
                Wystarczy, że znajdziesz klocek o nazwie <b>Tekst</b>, klikniesz w niego i zmienisz treść w oknie, które wygląda zupełnie jak Word. Następnie kliknij "Zapisz stronę" w prawym górnym rogu.
            </p>
        </div>

        <div class="bg-white p-6 rounded-xl shadow-sm border border-gray-200">
            <h3 class="text-xl font-bold text-green-600 mb-3 flex items-center gap-2"><span>🖼️</span> Jak wgrać nowe zdjęcie?</h3>
            <p class="text-gray-700 leading-relaxed mb-4">
                Możesz wgrać zdjęcia bezpośrednio w <b>Menedżerze Mediów (Pliki)</b>, przeciągając je z pulpitu. Alternatywnie, podczas edycji strony w bloku <b>"Obrazek"</b>, wystarczy kliknąć przycisk <b>📂</b> (folderu), aby wybrać już wgrane zdjęcie lub wgrać zupełnie nowe klikając strzałkę w górę.
            </p>
        </div>

        <div class="bg-white p-6 rounded-xl shadow-sm border border-gray-200">
            <h3 class="text-xl font-bold text-purple-600 mb-3 flex items-center gap-2"><span>📐</span> Czym są Szablony i "Drop Zony"?</h3>
            <p class="text-gray-700 leading-relaxed">
                Szablony to przygotowane przez programistę sztywne układy graficzne (np. baner z paralaksą). Posiadają one wyznaczone <b>strefy (Drop-Zones)</b> zaznaczone przerywaną linią. Jako użytkownik możesz wciągać swoje klocki z prawego paska (np. Formularz, Galerię, Tekst) <b>tylko do tych wyznaczonych stref</b>. Zapewnia to, że nigdy nie popsujesz układu graficznego witryny!
            </p>
        </div>
        
        <div class="bg-white p-6 rounded-xl shadow-sm border border-gray-200">
            <h3 class="text-xl font-bold text-red-500 mb-3 flex items-center gap-2"><span>📝</span> Gdzie znajdę odpowiedzi klientów z Formularzy?</h3>
            <p class="text-gray-700 leading-relaxed">
                Wszystkie dane przesyłane przez formularze kontaktowe na stronie są automatycznie sprawdzane i zapisywane na serwerze. Odpowiedzi możesz przeczytać w zakładce <b>Formularze -> View Submissions</b>.
            </p>
        </div>
    </div>
</div>